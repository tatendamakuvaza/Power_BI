def main():
    rows = []
    for fname in sorted(os.listdir(RAW)):
        if not fname.endswith(".csv"):
            continue
        table = fname[:-4]
        with open(os.path.join(RAW, fname), newline="", encoding="utf-8") as f:
            header = next(csv.reader(f))
        desc = D.get(table, {})
        for col in header:
            rows.append({
                "Table": table,
                "Column": col,
                "Description": desc.get(col, ""),
                "Source file": f"data/raw/{fname}",
            })
    path = os.path.join(OUT, "DataDictionary.csv")
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["Table", "Column", "Description", "Source file"])
        w.writeheader()
        w.writerows(rows)
    missing = sum(1 for r in rows if not r["Description"])
    print(f"  DataDictionary.csv - {len(rows)} fields, {missing} without a note")
    for r in rows:
        if not r["Description"]:
            print("   missing:", r["Table"], r["Column"])


if __name__ == "__main__":
    main()
